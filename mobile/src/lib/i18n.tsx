const DICTS: Record<Lang, Dict> = { ar, en }

/** اللغة الحالية على مستوى الوحدة، ليعمل t() خارج مكوّنات React أيضًا. */
let current: Lang = 'ar'

export function getLang(): Lang {
  return current
}

export function isRtl(): boolean {
  return current === 'ar'
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const raw = DICTS[current][key] ?? DICTS.en[key] ?? key
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`))
}

const STORAGE_KEY = 'cleanshelf.lang'

export function loadLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'ar' || saved === 'en') return saved
  } catch {
    // تجاهل
  }
  return typeof navigator !== 'undefined' && navigator.language?.startsWith('en') ? 'en' : 'ar'
}

function applyLangToDocument(lang: Lang): void {
  current = lang
  const root = document.documentElement
  root.lang = lang
  root.dir = lang === 'ar' ? 'rtl' : 'ltr'
  try {
    localStorage.setItem(STORAGE_KEY, lang)
  } catch {
    // تجاهل
  }
}

interface I18nValue {
  lang: Lang
  setLang: (lang: Lang) => void
  t: typeof t
  dir: 'rtl' | 'ltr'
}

const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children }: { children: React.ReactNode }): JSX.Element {
  const [lang, setLangState] = useState<Lang>(loadLang)

  // نضبط اللغة قبل رسم الأبناء حتى يقرأ t() القيمة الصحيحة في نفس الدورة
  current = lang

  useEffect(() => {
    applyLangToDocument(lang)
  }, [lang])

  const setLang = useCallback((next: Lang) => {
    applyLangToDocument(next)
    setLangState(next)
  }, [])

  const value = useMemo<I18nValue>(() => ({ lang, setLang, t, dir: lang === 'ar' ? 'rtl' : 'ltr' }), [lang, setLang])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n خارج I18nProvider')
  return ctx
}
